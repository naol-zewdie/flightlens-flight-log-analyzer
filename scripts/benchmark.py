"""Regenerate the fault benchmark and docs/validation.md.

    uv run python scripts/benchmark.py              # writes docs/validation.md
    uv run python scripts/benchmark.py --keep out/  # also keep the generated logs

Exit code 1 if any benchmark log is not fully correct (CI uses this).
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from flightlens import __version__, validate  # noqa: E402
from flightlens.sim.benchmark import build  # noqa: E402

INTRO = """\
Generated by `scripts/benchmark.py` with FlightLens {version} on {date}. Do not edit by hand.

## What this measures

Each benchmark log is an ArduPilot `.bin` with **one injected fault** (or none),
written by `flightlens/sim/benchmark.py` with seeded sensor noise. Every log is labelled
with the findings FlightLens must report (check, severity and time window) and
is scored *exhaustively*: any other Attention or Problem is a false alarm.

- **Healthy flights**, including flights just inside a limit (vibration 25 m/s²
  against a 30 m/s² limit, 3.6 V per cell against 3.5 V, a 4% motor offset), measure
  false alarms.
- **Faults at both severities** (vibration 42 and 75 m/s², GPS degraded and lost)
  measure whether the severity, not just the detection, is right.
- **Detected** means the check reported Attention or Problem inside the fault
  window ± tolerance; **right severity** means it also matched the label.

**Limits of this benchmark.** These logs test the detection logic against fault
signatures as modelled in the generator; they cannot show that real faults look
like that. That evidence comes from the real labelled logs
([real-log-results.md](real-log-results.md)) and from SITL fault injection
(`scripts/sitl_campaign.py`). Run the same scoring on any labelled set with
`flightlens validate <manifest-or-folder>`.

CI runs this benchmark (`tests/test_validation.py`) and fails if any log is
not fully correct, so a threshold or logic regression cannot ship.

"""


def replay_section(folder: Path) -> str:
    """Replay accuracy against the known-manoeuvre flight, build time and payload size."""
    import gzip
    import math
    import time

    import numpy as np

    from flightlens import parsers
    from flightlens.replay import build_replay
    from flightlens.sim import manoeuvre
    from flightlens.sim.telemetry import telemetry

    known = []
    onboard = manoeuvre.manoeuvre_log(folder / "manoeuvres.bin")
    for path in (onboard, telemetry(parsers.load(onboard), folder / "manoeuvres.tlog")):
        c = build_replay(parsers.load(path)).columns
        att = pos = 0.0
        for i in range(c["t"].size):
            g = manoeuvre.truth(float(c["t"][i]))
            if c["valid_att"][i]:
                for got, want in ((c["roll"][i], g.roll), (c["pitch"][i], g.pitch),
                                  (c["yaw"][i], g.yaw)):  # fmt: skip
                    att = max(att, abs((float(got) - want + 180) % 360 - 180))
            if c["valid_pos"][i] and np.isfinite(c["up"][i]):
                here = (c["east"][i], c["north"][i], c["up"][i])
                pos = max(pos, math.dist(here, (g.east, g.north, g.up)))
        known.append((path.suffix, att, pos))

    rows = []
    for log in sorted(folder.glob("copter-*.bin"))[:6] + sorted(folder.glob("*.tlog"))[:2]:
        flight = parsers.load(log)
        t0 = time.perf_counter()
        r = build_replay(flight)
        seconds = time.perf_counter() - t0
        body = b"".join(
            np.ascontiguousarray(r.columns[c], dtype="<f4").tobytes() for c in r.meta["columns"]
        )
        minutes = max((r.meta["end"] - r.meta["start"]) / 60, 1e-9)
        per_hour = len(gzip.compress(body, 6)) / 1e6 * 60 / minutes
        rows.append((log.name, minutes, r.meta["rate_hz"], seconds, per_hour))

    out = [
        "## Replay",
        "",
        "Accuracy against the scripted flight in `flightlens/sim/manoeuvre.py` (a 30° roll,",
        "a 45° pitch, a 90° turn and a 20 m square, with exact ground truth). The plan's",
        "tolerance is 0.5° and 0.5 m.",
        "",
        "| Log | Worst attitude error | Worst position error |",
        "|---|---|---|",
    ]
    out += [f"| `{suffix}` | {a:.3f}° | {p:.3f} m |" for suffix, a, p in known]
    out += [
        "",
        "Build time and payload: the gzip-compressed table the browser downloads, scaled",
        "to one hour of flight (budget 5 MB).",
        "",
        "| Log | Minutes | Rate | Build | Payload per hour |",
        "|---|---|---|---|---|",
    ]
    out += [
        f"| `{name}` | {m:.1f} | {hz:g} Hz | {sec * 1000:.0f} ms | {mb:.1f} MB |"
        for name, m, hz, sec, mb in rows
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--keep", type=Path, help="write the logs here instead of a temp dir")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "validation.md")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        manifest = build(args.keep or Path(tmp))
        outcomes = [validate.evaluate(c) for c in validate.load_manifest(manifest)]
        replay = replay_section(manifest.parent)

    body = validate.to_markdown(outcomes, "Validation benchmark")
    title, rest = body.split("\n", 1)
    date = datetime.now(UTC).date().isoformat()
    args.out.write_text(
        f"{title}\n\n{INTRO.format(version=__version__, date=date)}{rest.lstrip()}\n{replay}",
        encoding="utf-8",
    )
    passed = sum(o.passed for o in outcomes)
    print(f"{passed} of {len(outcomes)} logs fully correct -> {args.out}")
    return 0 if passed == len(outcomes) else 1


if __name__ == "__main__":
    raise SystemExit(main())
